-- Manual, position-aware player ratings derived from match statistics.
-- Each calculation run stores its learned model weights and validation metrics.
CREATE TABLE IF NOT EXISTS public.own_rating_runs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  season_id bigint NOT NULL REFERENCES public.seasons(id) ON DELETE RESTRICT,
  competition_id bigint NOT NULL REFERENCES public.competitions(id) ON DELETE RESTRICT,
  model_version text NOT NULL,
  stage_ids bigint[] NOT NULL DEFAULT '{}',
  training_samples integer NOT NULL DEFAULT 0,
  rated_samples integer NOT NULL DEFAULT 0,
  cross_validation_mae numeric(7,4),
  cross_validation_rmse numeric(7,4),
  position_models jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS own_rating_runs_scope_idx
  ON public.own_rating_runs (season_id, competition_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.own_match_ratings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id uuid NOT NULL REFERENCES public.own_rating_runs(id) ON DELETE CASCADE,
  participation_id bigint NOT NULL REFERENCES public.participations(id) ON DELETE CASCADE,
  match_id bigint NOT NULL REFERENCES public.matches(id) ON DELETE CASCADE,
  player_id bigint NOT NULL REFERENCES public.players(id) ON DELETE RESTRICT,
  position_id bigint NOT NULL REFERENCES public.positions(id) ON DELETE RESTRICT,
  own_rating numeric(5,3) NOT NULL CHECK (own_rating BETWEEN 0 AND 10),
  external_average numeric(5,3) CHECK (external_average IS NULL OR external_average BETWEEN 0 AND 10),
  absolute_error numeric(6,3),
  calculation_version text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (run_id, participation_id)
);

CREATE INDEX IF NOT EXISTS own_match_ratings_run_idx
  ON public.own_match_ratings (run_id, match_id);
CREATE INDEX IF NOT EXISTS own_match_ratings_player_idx
  ON public.own_match_ratings (player_id, match_id DESC);

