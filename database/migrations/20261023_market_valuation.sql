-- Value90 indicative player market valuation, version V90-MV-1.0.
-- Apply in Supabase SQL Editor before deploying the matching application change.
-- The amount is an internal estimate, not a transfer fee or third-party market quote.

CREATE TABLE IF NOT EXISTS public.market_valuation_runs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  period_start date NOT NULL,
  run_source text NOT NULL CHECK (run_source IN ('scheduled', 'manual')),
  model_version text NOT NULL DEFAULT 'V90-MV-1.0',
  season_id bigint REFERENCES public.seasons(id) ON DELETE SET NULL,
  player_count integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL DEFAULT 'completed' CHECK (status IN ('running', 'completed', 'no_data', 'failed'))
);

CREATE INDEX IF NOT EXISTS market_valuation_runs_period_idx
  ON public.market_valuation_runs (period_start DESC, created_at DESC);

CREATE TABLE IF NOT EXISTS public.player_market_values (
  player_id bigint PRIMARY KEY REFERENCES public.players(id) ON DELETE CASCADE,
  team_id bigint REFERENCES public.teams(id) ON DELETE SET NULL,
  current_value_eur bigint NOT NULL CHECK (current_value_eur >= 0),
  previous_value_eur bigint CHECK (previous_value_eur IS NULL OR previous_value_eur >= 0),
  change_percent numeric(8, 2),
  rating_last_30_days numeric(5, 3),
  rating_current_season numeric(5, 3) NOT NULL,
  market_rating numeric(5, 3) NOT NULL,
  age_at_valuation integer,
  eligible_matches integer NOT NULL DEFAULT 0,
  run_id uuid NOT NULL REFERENCES public.market_valuation_runs(id) ON DELETE RESTRICT,
  period_start date NOT NULL,
  model_version text NOT NULL DEFAULT 'V90-MV-1.0',
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS player_market_values_team_idx
  ON public.player_market_values (team_id, current_value_eur DESC);
CREATE INDEX IF NOT EXISTS player_market_values_value_idx
  ON public.player_market_values (current_value_eur DESC);
CREATE INDEX IF NOT EXISTS fact_player_v90_market_idx
  ON public.fact_player_v90_match (match_id, player_id)
  WHERE active = true AND status = 'CALCULATED';
CREATE INDEX IF NOT EXISTS matches_market_season_date_idx
  ON public.matches (season_id, date);

CREATE TABLE IF NOT EXISTS public.player_market_value_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id bigint NOT NULL REFERENCES public.players(id) ON DELETE CASCADE,
  team_id bigint REFERENCES public.teams(id) ON DELETE SET NULL,
  run_id uuid NOT NULL REFERENCES public.market_valuation_runs(id) ON DELETE CASCADE,
  period_start date NOT NULL,
  value_eur bigint NOT NULL CHECK (value_eur >= 0),
  rating_last_30_days numeric(5, 3),
  rating_current_season numeric(5, 3) NOT NULL,
  market_rating numeric(5, 3) NOT NULL,
  age_at_valuation integer,
  model_version text NOT NULL DEFAULT 'V90-MV-1.0',
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (player_id, run_id)
);

CREATE INDEX IF NOT EXISTS player_market_value_history_player_idx
  ON public.player_market_value_history (player_id, period_start DESC, created_at DESC);

ALTER TABLE public.market_valuation_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.player_market_values ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.player_market_value_history ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can read current player market estimates" ON public.player_market_values;
CREATE POLICY "Public can read current player market estimates"
  ON public.player_market_values FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "Public can read player market estimate history" ON public.player_market_value_history;
CREATE POLICY "Public can read player market estimate history"
  ON public.player_market_value_history FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "Authenticated users can read market valuation runs" ON public.market_valuation_runs;
CREATE POLICY "Authenticated users can read market valuation runs"
  ON public.market_valuation_runs FOR SELECT TO authenticated USING (true);

GRANT SELECT ON public.player_market_values, public.player_market_value_history TO anon, authenticated;
GRANT SELECT ON public.market_valuation_runs TO authenticated;

CREATE OR REPLACE FUNCTION public.run_market_valuation(p_force boolean DEFAULT false)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_local_date date := (now() AT TIME ZONE 'Europe/Madrid')::date;
  v_period_start date;
  v_season_id bigint;
  v_run_id uuid;
  v_count integer := 0;
  v_source text := CASE WHEN p_force THEN 'manual' ELSE 'scheduled' END;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('value90-market-valuation'));

  IF NOT p_force AND (EXTRACT(ISODOW FROM v_local_date) <> 2 OR EXTRACT(DAY FROM v_local_date) > 7) THEN
    RETURN jsonb_build_object('status', 'not_due', 'checked_on', v_local_date);
  END IF;

  v_period_start := date_trunc('month', v_local_date)::date;

  IF NOT p_force AND EXISTS (
    SELECT 1 FROM public.market_valuation_runs
    WHERE period_start = v_period_start AND run_source = 'scheduled' AND status = 'completed'
  ) THEN
    RETURN jsonb_build_object('status', 'already_completed', 'period_start', v_period_start);
  END IF;

  SELECT id INTO v_season_id
  FROM public.seasons
  WHERE active = true
  ORDER BY start_date DESC NULLS LAST, id DESC
  LIMIT 1;

  IF v_season_id IS NULL THEN
    RETURN jsonb_build_object('status', 'no_active_season', 'checked_on', v_local_date);
  END IF;

  INSERT INTO public.market_valuation_runs (period_start, run_source, season_id, status)
  VALUES (v_period_start, v_source, v_season_id, 'running')
  RETURNING id INTO v_run_id;

  DROP TABLE IF EXISTS pg_temp.value90_market_candidates;
  CREATE TEMP TABLE value90_market_candidates ON COMMIT DROP AS
  WITH player_ratings AS (
    SELECT
      f.player_id,
      SUM(f.weighted_contribution) FILTER (WHERE m.date >= v_local_date - 30)::numeric
        / NULLIF(SUM(f.total_weight) FILTER (WHERE m.date >= v_local_date - 30), 0) AS recent_rating,
      SUM(f.weighted_contribution)::numeric / NULLIF(SUM(f.total_weight), 0) AS season_rating,
      COUNT(DISTINCT f.match_id)::integer AS season_matches,
      COUNT(DISTINCT f.match_id) FILTER (WHERE m.date >= v_local_date - 30)::integer AS recent_matches
    FROM public.fact_player_v90_match AS f
    JOIN public.matches AS m ON m.id = f.match_id
    WHERE f.active = true
      AND f.status = 'CALCULATED'
      AND m.season_id = v_season_id
      AND f.weighted_contribution IS NOT NULL
      AND f.total_weight > 0
    GROUP BY f.player_id
  ), eligible AS (
    SELECT
      p.id AS player_id,
      current_team.team_id,
      pr.recent_rating,
      pr.season_rating,
      CASE
        WHEN pr.recent_rating IS NULL THEN pr.season_rating
        ELSE (pr.recent_rating * 0.60 + pr.season_rating * 0.40)
      END AS market_rating,
      pr.season_matches,
      pr.recent_matches,
      CASE WHEN p.birth_date IS NULL THEN NULL
        ELSE EXTRACT(YEAR FROM age(v_local_date, p.birth_date::date))::integer
      END AS age_at_valuation
    FROM player_ratings AS pr
    JOIN public.players AS p ON p.id = pr.player_id AND p.active = true
    LEFT JOIN LATERAL (
      SELECT h.team_id
      FROM public.hist_player_teams AS h
      WHERE h.player_id = p.id AND h.season_id = v_season_id AND h.active = true
      ORDER BY h.id DESC
      LIMIT 1
    ) AS current_team ON true
    WHERE pr.season_rating BETWEEN 0 AND 10
  ), calculated AS (
    SELECT
      eligible.*,
      CASE
        WHEN age_at_valuation IS NULL THEN 1.00
        WHEN age_at_valuation <= 17 THEN 0.55
        WHEN age_at_valuation = 18 THEN 0.70
        WHEN age_at_valuation = 19 THEN 0.82
        WHEN age_at_valuation = 20 THEN 0.92
        WHEN age_at_valuation = 21 THEN 1.02
        WHEN age_at_valuation BETWEEN 22 AND 27 THEN 1.15
        WHEN age_at_valuation = 28 THEN 1.10
        WHEN age_at_valuation = 29 THEN 1.02
        WHEN age_at_valuation = 30 THEN 0.92
        WHEN age_at_valuation = 31 THEN 0.80
        WHEN age_at_valuation = 32 THEN 0.68
        WHEN age_at_valuation = 33 THEN 0.56
        WHEN age_at_valuation = 34 THEN 0.46
        WHEN age_at_valuation = 35 THEN 0.38
        ELSE 0.30
      END AS age_factor
    FROM eligible
  )
  SELECT
    player_id,
    team_id,
    recent_rating,
    season_rating,
    market_rating,
    season_matches,
    recent_matches,
    age_at_valuation,
    GREATEST(50000, LEAST(500000000,
      round((1000000 * power(3.25::numeric, market_rating - 5) * age_factor) / 50000) * 50000
    ))::bigint AS value_eur
  FROM calculated
  WHERE market_rating BETWEEN 0 AND 10;

  SELECT COUNT(*)::integer INTO v_count FROM pg_temp.value90_market_candidates;

  IF v_count = 0 THEN
    UPDATE public.market_valuation_runs SET status = 'no_data', player_count = 0 WHERE id = v_run_id;
    RETURN jsonb_build_object('status', 'no_data', 'run_id', v_run_id, 'season_id', v_season_id);
  END IF;

  INSERT INTO public.player_market_value_history (
    player_id, team_id, run_id, period_start, value_eur,
    rating_last_30_days, rating_current_season, market_rating,
    age_at_valuation
  )
  SELECT
    candidate.player_id, candidate.team_id, v_run_id, v_period_start, candidate.value_eur,
    round(candidate.recent_rating, 3), round(candidate.season_rating, 3), round(candidate.market_rating, 3),
    candidate.age_at_valuation
  FROM pg_temp.value90_market_candidates AS candidate;

  INSERT INTO public.player_market_values AS existing (
    player_id, team_id, current_value_eur, previous_value_eur, change_percent,
    rating_last_30_days, rating_current_season, market_rating,
    age_at_valuation, eligible_matches, run_id, period_start, updated_at
  )
  SELECT
    candidate.player_id, candidate.team_id, candidate.value_eur, current_value.current_value_eur,
    CASE WHEN current_value.current_value_eur > 0
      THEN round(((candidate.value_eur - current_value.current_value_eur)::numeric / current_value.current_value_eur) * 100, 2)
      ELSE NULL END,
    round(candidate.recent_rating, 3), round(candidate.season_rating, 3), round(candidate.market_rating, 3),
    candidate.age_at_valuation, candidate.season_matches,
    v_run_id, v_period_start, now()
  FROM pg_temp.value90_market_candidates AS candidate
  LEFT JOIN public.player_market_values AS current_value ON current_value.player_id = candidate.player_id
  ON CONFLICT (player_id) DO UPDATE SET
    team_id = EXCLUDED.team_id,
    current_value_eur = EXCLUDED.current_value_eur,
    previous_value_eur = existing.current_value_eur,
    change_percent = CASE WHEN existing.current_value_eur > 0
      THEN round(((EXCLUDED.current_value_eur - existing.current_value_eur)::numeric / existing.current_value_eur) * 100, 2)
      ELSE NULL END,
    rating_last_30_days = EXCLUDED.rating_last_30_days,
    rating_current_season = EXCLUDED.rating_current_season,
    market_rating = EXCLUDED.market_rating,
    age_at_valuation = EXCLUDED.age_at_valuation,
    eligible_matches = EXCLUDED.eligible_matches,
    run_id = EXCLUDED.run_id,
    period_start = EXCLUDED.period_start,
    updated_at = EXCLUDED.updated_at;

  UPDATE public.market_valuation_runs SET status = 'completed', player_count = v_count WHERE id = v_run_id;
  RETURN jsonb_build_object('status', 'completed', 'run_id', v_run_id, 'period_start', v_period_start, 'season_id', v_season_id, 'player_count', v_count, 'model_version', 'V90-MV-1.0');
END;
$$;

REVOKE ALL ON FUNCTION public.run_market_valuation(boolean) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.run_market_valuation(boolean) TO authenticated;

-- Check daily at 05:00 UTC (06:00 Madrid in winter, 07:00 in summer).
-- The function itself only runs on the first Tuesday in Europe/Madrid and is idempotent.
CREATE EXTENSION IF NOT EXISTS pg_cron WITH SCHEMA pg_catalog;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'value90-monthly-market-valuation') THEN
    PERFORM cron.unschedule(jobid) FROM cron.job WHERE jobname = 'value90-monthly-market-valuation';
  END IF;
  PERFORM cron.schedule(
    'value90-monthly-market-valuation',
    '0 5 * * *',
    'SELECT public.run_market_valuation(false);'
  );
END;
$$;
