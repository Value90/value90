-- Published sports data is readable publicly. Authenticated sessions manage the
-- sports data; account creation should remain disabled in Supabase Auth.
DO $$
DECLARE
  table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'countries','competitions','competition_weights','rival_weights','participation_weights',
    'teams','positions','players','seasons','stages','hist_team_competitions',
    'hist_player_teams','matches','participations','match_ratings','player_match_stats',
    'fact_player_v90_match'
  ] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('GRANT SELECT ON public.%I TO anon, authenticated', table_name);
    EXECUTE format('GRANT INSERT, UPDATE, DELETE ON public.%I TO authenticated', table_name);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', table_name || '_public_read', table_name);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO anon, authenticated USING (true)', table_name || '_public_read', table_name);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', table_name || '_authenticated_manage', table_name);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR ALL TO authenticated USING (lower(coalesce(auth.jwt() ->> ''email'', '''')) = ''pastues@icloud.com'') WITH CHECK (lower(coalesce(auth.jwt() ->> ''email'', '''')) = ''pastues@icloud.com'')', table_name || '_authenticated_manage', table_name);
  END LOOP;

  FOREACH table_name IN ARRAY ARRAY['ai_recognition_results','ai_recognition_corrections'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO authenticated', table_name);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', table_name || '_authenticated_manage', table_name);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR ALL TO authenticated USING (lower(coalesce(auth.jwt() ->> ''email'', '''')) = ''pastues@icloud.com'') WITH CHECK (lower(coalesce(auth.jwt() ->> ''email'', '''')) = ''pastues@icloud.com'')', table_name || '_authenticated_manage', table_name);
  END LOOP;
END $$;

