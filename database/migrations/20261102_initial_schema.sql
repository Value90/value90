-- Value90 initial schema for the replacement Supabase project.
-- Reconstructed from the application queries and the read-only REST export.
-- Apply this before the market valuation and Highlightly migrations.

CREATE TABLE IF NOT EXISTS public.countries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  code text,
  fifa_code text,
  continent text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.competitions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  short_name text,
  country_id bigint REFERENCES public.countries(id) ON DELETE SET NULL,
  competition_type text NOT NULL,
  confederation text,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.competition_weights (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  competition_id bigint NOT NULL REFERENCES public.competitions(id) ON DELETE CASCADE,
  peso_v90 numeric NOT NULL,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.rival_weights (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  classification text NOT NULL,
  min_difference numeric,
  max_difference numeric,
  peso_v90 numeric NOT NULL,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.participation_weights (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  min_minutes integer NOT NULL,
  max_minutes integer NOT NULL,
  peso_v90 numeric NOT NULL,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT participation_weights_minutes_range CHECK (min_minutes >= 0 AND max_minutes >= min_minutes)
);

CREATE TABLE IF NOT EXISTS public.teams (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  short_name text,
  country_id bigint REFERENCES public.countries(id) ON DELETE SET NULL,
  confederation text,
  city text,
  stadium text,
  type text,
  active boolean NOT NULL DEFAULT true,
  display_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  competition_id bigint REFERENCES public.competitions(id) ON DELETE SET NULL,
  foundation_year integer,
  stadium_capacity integer,
  CONSTRAINT teams_foundation_year_range CHECK (foundation_year IS NULL OR foundation_year BETWEEN 1800 AND 2100),
  CONSTRAINT teams_stadium_capacity_nonnegative CHECK (stadium_capacity IS NULL OR stadium_capacity >= 0)
);

CREATE TABLE IF NOT EXISTS public.positions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  short_name text,
  display_order integer NOT NULL DEFAULT 0,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.players (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  short_name text,
  country_id bigint REFERENCES public.countries(id) ON DELETE SET NULL,
  birth_date text,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.seasons (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  start_date date,
  end_date date,
  active boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.stages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id bigint NOT NULL REFERENCES public.seasons(id) ON DELETE CASCADE,
  name text NOT NULL,
  display_order integer NOT NULL DEFAULT 0,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.hist_team_competitions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id bigint NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
  competition_id bigint NOT NULL REFERENCES public.competitions(id) ON DELETE CASCADE,
  season_id bigint NOT NULL REFERENCES public.seasons(id) ON DELETE CASCADE,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.hist_player_teams (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id bigint NOT NULL REFERENCES public.players(id) ON DELETE CASCADE,
  team_id bigint NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
  season_id bigint NOT NULL REFERENCES public.seasons(id) ON DELETE CASCADE,
  shirt_number integer NOT NULL DEFAULT 0,
  position_id bigint NOT NULL REFERENCES public.positions(id) ON DELETE RESTRICT,
  start_date date,
  end_date date,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.matches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  competition_id bigint NOT NULL REFERENCES public.competitions(id) ON DELETE RESTRICT,
  season_id bigint NOT NULL REFERENCES public.seasons(id) ON DELETE RESTRICT,
  stage_id bigint NOT NULL REFERENCES public.stages(id) ON DELETE RESTRICT,
  home_team_id bigint NOT NULL REFERENCES public.teams(id) ON DELETE RESTRICT,
  away_team_id bigint NOT NULL REFERENCES public.teams(id) ON DELETE RESTRICT,
  home_score integer NOT NULL DEFAULT 0,
  away_score integer NOT NULL DEFAULT 0,
  date timestamptz NOT NULL,
  stadium text,
  status text NOT NULL DEFAULT 'scheduled',
  created_at timestamptz NOT NULL DEFAULT now(),
  match_duration integer NOT NULL DEFAULT 90,
  home_penalty_score integer,
  away_penalty_score integer,
  CONSTRAINT matches_distinct_teams CHECK (home_team_id <> away_team_id),
  CONSTRAINT matches_nonnegative_scores CHECK (home_score >= 0 AND away_score >= 0)
);

CREATE TABLE IF NOT EXISTS public.participations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id bigint NOT NULL REFERENCES public.matches(id) ON DELETE CASCADE,
  player_id bigint NOT NULL REFERENCES public.players(id) ON DELETE RESTRICT,
  team_id bigint NOT NULL REFERENCES public.teams(id) ON DELETE RESTRICT,
  position_id bigint NOT NULL REFERENCES public.positions(id) ON DELETE RESTRICT,
  shirt_number integer NOT NULL DEFAULT 0,
  is_starting_xi boolean NOT NULL DEFAULT false,
  minutes_played integer NOT NULL DEFAULT 0,
  captain boolean NOT NULL DEFAULT false,
  substitute_in_minute integer,
  substitute_out_minute integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT participations_minutes_nonnegative CHECK (minutes_played >= 0)
);

CREATE TABLE IF NOT EXISTS public.match_ratings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id bigint NOT NULL REFERENCES public.matches(id) ON DELETE CASCADE,
  player_id bigint NOT NULL REFERENCES public.players(id) ON DELETE RESTRICT,
  participation_id bigint NOT NULL REFERENCES public.participations(id) ON DELETE CASCADE,
  marca_rating numeric,
  as_rating numeric,
  sofascore_rating numeric,
  flashscore_rating numeric,
  external_average numeric,
  value90_match_rating numeric,
  final_match_rating numeric,
  confidence numeric,
  calculation_version text,
  calculated_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.player_match_stats (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participation_id bigint NOT NULL REFERENCES public.participations(id) ON DELETE CASCADE,
  shots integer NOT NULL DEFAULT 0,
  shots_on_target integer NOT NULL DEFAULT 0,
  dribbles integer NOT NULL DEFAULT 0,
  dribbles_completed integer NOT NULL DEFAULT 0,
  assists integer NOT NULL DEFAULT 0,
  duels integer NOT NULL DEFAULT 0,
  duels_won integer NOT NULL DEFAULT 0,
  clearances integer NOT NULL DEFAULT 0,
  saves integer NOT NULL DEFAULT 0,
  tackles integer NOT NULL DEFAULT 0,
  recoveries integer NOT NULL DEFAULT 0,
  passes integer NOT NULL DEFAULT 0,
  passes_completed integer NOT NULL DEFAULT 0,
  goal_errors integer NOT NULL DEFAULT 0,
  yellow_cards integer NOT NULL DEFAULT 0,
  red_cards integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  goals integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.fact_player_v90_match (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participation_id bigint NOT NULL REFERENCES public.participations(id) ON DELETE CASCADE,
  player_id bigint NOT NULL REFERENCES public.players(id) ON DELETE RESTRICT,
  match_id bigint NOT NULL REFERENCES public.matches(id) ON DELETE CASCADE,
  team_id bigint NOT NULL REFERENCES public.teams(id) ON DELETE RESTRICT,
  rival_team_id bigint NOT NULL REFERENCES public.teams(id) ON DELETE RESTRICT,
  external_average numeric,
  competition_weight numeric NOT NULL DEFAULT 0,
  rival_weight numeric NOT NULL DEFAULT 0,
  participation_weight numeric NOT NULL DEFAULT 0,
  total_weight numeric NOT NULL DEFAULT 0,
  weighted_contribution numeric,
  v90_match numeric,
  status text NOT NULL DEFAULT 'PENDING',
  calculation_version text,
  calculated_at timestamptz,
  active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS public.ai_recognition_results (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id bigint REFERENCES public.matches(id) ON DELETE SET NULL,
  recognition_type text NOT NULL CHECK (recognition_type IN ('participations', 'ratings')),
  source text,
  image_reference text,
  raw_response jsonb,
  request_context jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.ai_recognition_corrections (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  result_id bigint REFERENCES public.ai_recognition_results(id) ON DELETE SET NULL,
  match_id bigint REFERENCES public.matches(id) ON DELETE SET NULL,
  player_id bigint REFERENCES public.players(id) ON DELETE SET NULL,
  participation_id bigint REFERENCES public.participations(id) ON DELETE SET NULL,
  field_name text NOT NULL,
  detected_value jsonb,
  corrected_value jsonb,
  correction_type text NOT NULL CHECK (correction_type IN ('player_identification', 'participation_status', 'substitute_in_minute', 'substitute_out_minute', 'captain', 'rating', 'other')),
  confidence numeric,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'rejected')),
  created_by text,
  created_at timestamptz NOT NULL DEFAULT now(),
  confirmed_at timestamptz
);

